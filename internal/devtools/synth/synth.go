// Name returns a plausible display name.
func (g *Gen) Name() string {
	name := pick(g, firstNames) + " " + pick(g, lastNames)
	if g.r.IntN(20) == 0 {
		name += " " + pick(g, emoji)
	}
	return name
}

// Sentence returns between minWords and maxWords words, occasionally with
// emoji and punctuation.
func (g *Gen) Sentence(minWords, maxWords int) string {
	n := minWords
	if maxWords > minWords {
		n += g.r.IntN(maxWords - minWords + 1)
	}
	var b strings.Builder
	for i := range n {
		if i > 0 {
			b.WriteByte(' ')
		}
		if g.r.IntN(12) == 0 {
			b.WriteString(pick(g, emoji))
			continue
		}
		b.WriteString(pick(g, words))
	}
	switch g.r.IntN(6) {
	case 0:
		b.WriteByte('?')
	case 1:
		b.WriteByte('!')
	}
	return b.String()
}

// Message returns a message body whose length follows a chat-like
// distribution: mostly short, sometimes long, rarely multi-line.
func (g *Gen) Message() string {
	switch p := g.r.IntN(100); {
	case p < 60:
		return g.Sentence(1, 8)
	case p < 90:
		return g.Sentence(8, 30)
	case p < 98:
		return g.Sentence(30, 120)
	default:
		lines := 2 + g.r.IntN(5)
		parts := make([]string, lines)
		for i := range parts {
			parts[i] = g.Sentence(2, 12)
		}
		return strings.Join(parts, "\n")
	}
}

// WAID returns a WhatsApp-style message ID (uppercase hex, as generated by
// WhatsApp Web clients).
func (g *Gen) WAID() domain.WAMessageID {
	return domain.WAMessageID(fmt.Sprintf("3EB0%016X", g.r.Uint64()))
}

// PN returns a phone-number JID in the Turkish +90 5xx range.
func (g *Gen) PN() domain.JID {
	return domain.JID(fmt.Sprintf("905%09d@%s", g.r.IntN(1_000_000_000), domain.ServerPN))
}

// LID returns a linked-identity JID.
func (g *Gen) LID() domain.JID {
	return domain.JID(fmt.Sprintf("%d@%s", 100_000_000_000_000+g.r.Int64N(900_000_000_000_000), domain.ServerLID))
}

// GroupJID returns a group JID.
func (g *Gen) GroupJID() domain.JID {
	return domain.JID(fmt.Sprintf("120363%012d@%s", g.r.Int64N(1_000_000_000_000), domain.ServerGroup))
}

// GroupTitle returns a plausible group subject.
func (g *Gen) GroupTitle() string {
	titles := []string{"Aile", "İş", "Proje Ekibi", "Komşular", "Okul Velileri", "Futbol", "Kitap Kulübü", "Family", "Team", "Friends"}
	t := pick(g, titles)
	if g.r.IntN(3) == 0 {
		t += " " + pick(g, emoji)
	}
	return t
}

func pick[T any](g *Gen, s []T) T { return s[g.r.IntN(len(s))] }
