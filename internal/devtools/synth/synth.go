// Package synth generates deterministic synthetic data (names, text and
// WhatsApp-style identifiers) for the fake backend, the dataset generator
// and benchmarks. The same seed always yields the same sequence.
package synth

import (
	"fmt"
	"math/rand/v2"
	"strings"

	"github.com/Yaman-yagiz/tarcin/internal/domain"
)

// Gen is a deterministic generator. It is not safe for concurrent use.
type Gen struct {
	r *rand.Rand
}

// New returns a generator seeded with seed.
func New(seed uint64) *Gen {
	return &Gen{r: rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15))} //nolint:gosec // synthetic test data, not security-sensitive
}

// Rand exposes the underlying source for callers that need other
// distributions while keeping one deterministic stream.
func (g *Gen) Rand() *rand.Rand { return g.r }

